    private void selectValidationDataset() {
        JFileChooser chooser = new JFileChooser();
        chooser.setFileSelectionMode(JFileChooser.FILES_AND_DIRECTORIES);

        int result = chooser.showOpenDialog(frame);

        if (result != JFileChooser.APPROVE_OPTION) {
            return;
        }

        File selected = chooser.getSelectedFile();

        try {
            File dataYaml;

            if (selected.isDirectory()) {
                File directDataYaml = new File(selected, "data.yaml");

                if (directDataYaml.exists()) {
                    dataYaml = directDataYaml;
                } else {
                    dataYaml = buildValidationDatasetFromCorrectedAnnotations(selected);
                }
            } else {
                dataYaml = selected;
            }

            if (!dataYaml.exists() || !dataYaml.getName().equals("data.yaml")) {
                IJ.error(
                        "Invalid validation dataset",
                        "Please select either:\n\n" +
                                "- a YOLO data.yaml file\n" +
                                "- a YOLO dataset folder containing data.yaml\n" +
                                "- an image folder containing neuron_transfer_learning/annotations"
                );
                return;
            }

            validationDataYaml = dataYaml;

            if (outputDir == null) {
                outputDir = new File(dataYaml.getParentFile(), "model_comparison_output");
            }

            initializeLogFile();
            appendLog("Validation dataset selected: " + validationDataYaml.getAbsolutePath());

            updateFields();
            updateStatus("Validation dataset selected.");
            updateButtonState();

        } catch (Exception e) {
            logError("Could not prepare validation dataset: " + e.getMessage());
            IJ.handleException(e);
            updateStatus("Could not prepare validation dataset.");
        }
    }

    private File buildValidationDatasetFromCorrectedAnnotations(File imageFolder) throws IOException {
        File transferDir = new File(imageFolder, "neuron_transfer_learning");
        File annotationsDir = new File(transferDir, "annotations");

        if (!annotationsDir.exists()) {
            throw new IOException(
                    "No neuron_transfer_learning/annotations folder found in:\n" +
                            imageFolder.getAbsolutePath()
            );
        }

        File validationDatasetDir = new File(transferDir, "yolo_validation_dataset");
        File imagesValDir = new File(validationDatasetDir, "images/val");
        File labelsValDir = new File(validationDatasetDir, "labels/val");

        imagesValDir.mkdirs();
        labelsValDir.mkdirs();

        clearDirectory(imagesValDir);
        clearDirectory(labelsValDir);

        File[] files = imageFolder.listFiles();

        if (files == null) {
            throw new IOException("No files found in selected folder.");
        }

        int count = 0;

        for (File imageFile : files) {
            if (!imageFile.isFile() || !isSupportedImage(imageFile)) {
                continue;
            }

            String imageBaseName = getBaseName(imageFile);
            File latestAnnotation = getLatestAnnotationFileForValidation(annotationsDir, imageBaseName);

            if (latestAnnotation == null || !latestAnnotation.exists()) {
                appendLog("Skipping image without corrected annotation: " + imageFile.getName());
                continue;
            }

            String extension = getExtension(imageFile);
            File targetImage = new File(imagesValDir, imageBaseName + extension);
            File targetLabel = new File(labelsValDir, imageBaseName + ".txt");

            Files.copy(imageFile.toPath(), targetImage.toPath(), java.nio.file.StandardCopyOption.REPLACE_EXISTING);
            Files.copy(latestAnnotation.toPath(), targetLabel.toPath(), java.nio.file.StandardCopyOption.REPLACE_EXISTING);

            appendLog("Validation sample added: " + imageFile.getName());
            count++;
        }

        if (count == 0) {
            throw new IOException(
                    "No corrected annotations found.\n\n" +
                            "Open the Transfer Learning Assistant, correct images and save corrections first."
            );
        }

        File dataYaml = new File(validationDatasetDir, "data.yaml");

        try (PrintWriter writer = new PrintWriter(new FileWriter(dataYaml))) {
            writer.println("path: \"" + validationDatasetDir.getAbsolutePath().replace("\\", "/") + "\"");
            writer.println("train: images/val");
            writer.println("val: images/val");
            writer.println("names:");
            writer.println("  0: neuron");
        }

        appendLog("Validation dataset built with " + count + " corrected images.");
        appendLog("Validation data.yaml: " + dataYaml.getAbsolutePath());

        return dataYaml;
    }

    private boolean isSupportedImage(File file) {
        if (file == null || !file.isFile()) {
            return false;
        }

        String name = file.getName();
        String lowerName = name.toLowerCase(java.util.Locale.ROOT);

        if (name.startsWith("._") ||
                name.startsWith(".") ||
                lowerName.equals("thumbs.db") ||
                lowerName.equals("desktop.ini") ||
                lowerName.equals(".ds_store")) {
            return false;
        }

        if (file.isHidden()) {
            return false;
        }

        return lowerName.endsWith(".png") ||
                lowerName.endsWith(".jpg") ||
                lowerName.endsWith(".jpeg") ||
                lowerName.endsWith(".tif") ||
                lowerName.endsWith(".tiff");
    }

    private String getBaseName(File file) {
        String name = file.getName();
        int dot = name.lastIndexOf(".");

        if (dot > 0) {
            name = name.substring(0, dot);
        }

        return sanitizeFileName(name);
    }

    private String sanitizeFileName(String name) {
        return name.replaceAll("[^a-zA-Z0-9._-]", "_");
    }

    private String getExtension(File file) {
        String name = file.getName();
        int dot = name.lastIndexOf(".");

        if (dot >= 0) {
            return name.substring(dot).toLowerCase(java.util.Locale.ROOT);
        }

        return ".png";
    }

    private File getLatestAnnotationFileForValidation(File annotationsDir, String imageBaseName) {
        File annotationFolder = new File(annotationsDir, imageBaseName);

        if (!annotationFolder.exists()) {
            return null;
        }

        File[] files = annotationFolder.listFiles((dir, name) ->
                name.startsWith("annotation_") && name.endsWith(".txt")
        );

        if (files == null || files.length == 0) {
            return null;
        }

        File latest = files[0];

        for (File file : files) {
            if (file.getName().compareTo(latest.getName()) > 0) {
                latest = file;
            }
        }

        return latest;
    }

    private void clearDirectory(File directory) throws IOException {
        if (directory == null || !directory.exists()) {
            return;
        }

        File[] files = directory.listFiles();

        if (files == null) {
            return;
        }

        for (File file : files) {
            if (file.isDirectory()) {
                clearDirectory(file);

                if (!file.delete()) {
                    appendLog("Could not delete directory: " + file.getAbsolutePath());
                }
            } else {
                Files.deleteIfExists(file.toPath());
            }
        }
    }

