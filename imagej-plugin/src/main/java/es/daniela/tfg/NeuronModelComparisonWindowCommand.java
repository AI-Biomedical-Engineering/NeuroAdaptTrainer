    private void runComparison() {
        if (pythonExe == null || pythonExe.trim().isEmpty()) {
            IJ.error("Python executable is not configured. Please run the installer first.");
            return;
        }

        if (compareScriptPath == null || compareScriptPath.trim().isEmpty()) {
            IJ.error("Comparison script is not configured.");
            return;
        }

        File pythonFile = new File(pythonExe);
        File compareScript = new File(compareScriptPath);

        if (!pythonFile.exists()) {
            IJ.error("Python executable not found:\n" + pythonExe);
            return;
        }

        if (!compareScript.exists()) {
            IJ.error(
                    "Comparison script not found:\n" +
                            compareScript.getAbsolutePath() +
                            "\n\nPlace compare_models.py next to retrain_model.py or add compare_script to config.properties."
            );
            return;
        }

        if (validationDataYaml == null || !validationDataYaml.exists()) {
            IJ.error("Please select a validation data.yaml first.");
            return;
        }

        File datasetRoot = validationDataYaml.getParentFile();

        File imagesTrainDir = new File(datasetRoot, "images/train");
        File labelsTrainDir = new File(datasetRoot, "labels/train");
        File imagesValDir = new File(datasetRoot, "images/val");
        File labelsValDir = new File(datasetRoot, "labels/val");

        boolean hasTrainStructure = imagesTrainDir.exists() && labelsTrainDir.exists();
        boolean hasValStructure = imagesValDir.exists() && labelsValDir.exists();

        if (!hasTrainStructure && !hasValStructure) {
            IJ.error(
                    "Invalid validation dataset",
                    "The selected dataset must contain either:\n\n" +
                            "images/val and labels/val\n\n" +
                            "or:\n\n" +
                            "images/train and labels/train\n\n" +
                            "Please generate or select a valid YOLO dataset."
            );
            return;
        }

        File selectedImagesDir = hasValStructure ? imagesValDir : imagesTrainDir;
        File selectedLabelsDir = hasValStructure ? labelsValDir : labelsTrainDir;

        int imageCount = countSupportedImages(selectedImagesDir);
        int labelCount = countTxtFiles(selectedLabelsDir);

        if (imageCount == 0 || labelCount == 0) {
            IJ.error(
                    "Empty validation dataset",
                    "The selected validation dataset does not contain valid image/label pairs.\n\n" +
                            "Images found: " + imageCount + "\n" +
                            "Labels found: " + labelCount + "\n\n" +
                            "If you selected an image folder, make sure corrections were saved first."
            );
            return;
        }

        if (baseModelFile == null || !baseModelFile.exists()) {
            IJ.error("Please select a valid base model.");
            return;
        }

        if (transferLearningModelFile == null || !transferLearningModelFile.exists()) {
            IJ.error("Please select a valid adapted model.");
            return;
        }

        if (outputDir == null) {
            outputDir = getDefaultOutputDir();
        }

        if (outputDir == null) {
            IJ.error("Please select an output folder.");
            return;
        }

        if (!outputDir.exists() && !outputDir.mkdirs()) {
            IJ.error("Could not create output folder:\n" + outputDir.getAbsolutePath());
            return;
        }

        initializeLogFile();

        metricsTableModel.setRowCount(0);

        comparisonRunning = true;
        updateStatus("Running external validation comparison...");
        updateButtonState();

        boolean useHardwareAcceleration =
                useHardwareAccelerationCheckBox != null && useHardwareAccelerationCheckBox.isSelected();

        new Thread(() -> {
            try {
                List<String> command = new ArrayList<>();

                command.add(pythonExe);
                command.add("-u");
                command.add(compareScriptPath);
                command.add(baseModelFile.getAbsolutePath());
                command.add(transferLearningModelFile.getAbsolutePath());
                command.add(validationDataYaml.getAbsolutePath());
                command.add(outputDir.getAbsolutePath());

                String selectedDevice;

                if (useHardwareAcceleration) {
                    selectedDevice = "auto_acceleration";
                } else {
                    selectedDevice = "cpu";
                }

                command.add(selectedDevice);

                appendLogSeparator();
                appendLog("Model comparison started.");
                appendLog("Validation data.yaml: " + validationDataYaml.getAbsolutePath());
                appendLog("Base model: " + baseModelFile.getAbsolutePath());
                appendLog("Adapted model: " + transferLearningModelFile.getAbsolutePath());
                appendLog("Output folder: " + outputDir.getAbsolutePath());
                appendLog("Requested validation device: " + selectedDevice);
                appendLog("Command: " + String.join(" ", command));
                appendLogSeparator();

                ProcessBuilder pb = new ProcessBuilder(command);
                pb.redirectErrorStream(true);

                Process process = pb.start();

                try (BufferedReader reader = new BufferedReader(
                        new InputStreamReader(process.getInputStream()))) {

                    String line;

                    while ((line = reader.readLine()) != null) {
                        logPython(line);
                    }
                }

                int exitCode = process.waitFor();

                if (exitCode != 0) {
                    throw new RuntimeException("Model comparison failed with exit code " + exitCode);
                }

                File metricsCsv = new File(outputDir, "model_comparison_metrics.csv");
                List<String[]> rows = readMetricsCsv(metricsCsv);

                SwingUtilities.invokeLater(() -> {
                    comparisonRunning = false;
                    fillMetricsTable(rows);
                    updateStatus("Model comparison completed.");
                    updateButtonState();

                    appendLog("Model comparison completed successfully.");
                    appendLog("Metrics CSV: " + metricsCsv.getAbsolutePath());

                    IJ.showMessage(
                            "Model comparison completed",
                            "Metrics saved to:\n" + metricsCsv.getAbsolutePath()
                    );
                });

            } catch (Exception e) {
                logError("Model comparison failed: " + e.getMessage());
                IJ.handleException(e);

                SwingUtilities.invokeLater(() -> {
                    comparisonRunning = false;
                    updateStatus("Model comparison failed.");
                    updateButtonState();
                });
            }
        }).start();
    }

    private int countSupportedImages(File directory) {
        if (directory == null || !directory.exists()) {
            return 0;
        }

        File[] files = directory.listFiles();

        if (files == null) {
            return 0;
        }

        int count = 0;

        for (File file : files) {
            if (file.isFile() && isSupportedImage(file)) {
                count++;
            }
        }

        return count;
    }

    private int countTxtFiles(File directory) {
        if (directory == null || !directory.exists()) {
            return 0;
        }

        File[] files = directory.listFiles();

        if (files == null) {
            return 0;
        }

        int count = 0;

        for (File file : files) {
            if (file.isFile() && file.getName().toLowerCase(java.util.Locale.ROOT).endsWith(".txt")) {
                count++;
            }
        }

        return count;
    }

    private List<String[]> readMetricsCsv(File csvFile) throws IOException {
        List<String[]> rows = new ArrayList<>();

        if (!csvFile.exists()) {
            throw new IOException("Metrics CSV not found: " + csvFile.getAbsolutePath());
        }

        try (BufferedReader reader = new BufferedReader(new FileReader(csvFile))) {
            String line = reader.readLine();

            while ((line = reader.readLine()) != null) {
                String[] parts = splitCsvLine(line);

                if (parts.length >= 4) {
                    rows.add(new String[]{parts[0], parts[1], parts[2], parts[3]});
                }
            }
        }

        return rows;
    }

    private String[] splitCsvLine(String line) {
        List<String> values = new ArrayList<>();
        StringBuilder current = new StringBuilder();

        boolean inQuotes = false;

        for (int i = 0; i < line.length(); i++) {
            char c = line.charAt(i);

            if (c == '"') {
                inQuotes = !inQuotes;
            } else if (c == ',' && !inQuotes) {
                values.add(current.toString());
                current.setLength(0);
            } else {
                current.append(c);
            }
        }

        values.add(current.toString());

        return values.toArray(new String[0]);
    }

    private void fillMetricsTable(List<String[]> rows) {
        metricsTableModel.setRowCount(0);

        for (String[] row : rows) {
            metricsTableModel.addRow(row);
        }
    }

